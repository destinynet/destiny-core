package destiny.core

/**
 * 命盤呈現密度 —— 各術數的呈現層 DTO 共用一組級數，
 * 好讓 render 端點只需要一個 `density` 參數，client 也只需認得一種型別。
 *
 * 每一級對各術數的具體含意由各自的 mapper 決定，但語意軸線一致：
 * 「並排概覽 → 單張細看 → 連雜訊都要」。
 *
 * |         | 紫微                          | 占星                          | 八字                                  |
 * |---------|-------------------------------|-------------------------------|---------------------------------------|
 * | COMPACT | 只有主星                       | 只有行星＋主要相位             | 只有四柱干支                            |
 * | FULL    | ＋六吉六煞＋乙級雜曜            | ＋交點／恆星／阿拉伯點          | ＋十神／藏干／大運／命宮／節氣位置／得分    |
 * | ALL     | ＋博士／長生／將前／歲前 48 顆   | ＋次要相位                     | ＋納音／空亡／大運藏干                   |
 */
enum class ChartDensity {
  /** 多張並排的概覽：只留最主要的資訊 */
  COMPACT,

  /** 單張細看：一般讀盤所需的完整資訊 */
  FULL,

  /** 連雜訊都要：星曜／相位全開，通常是 FULL 之上的一個開關 */
  ALL
}
